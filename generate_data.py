def generate_dataset(output_path="data/dishes.json"):
    """Формирует структурированный датасет и сохраняет его в JSON."""
    dishes = []
    for idx, item in enumerate(DISHES_TEMPLATE):
        dish = {
            "id": idx,
            "name": item["name"],
            "category": item["category"],
            "price": item["base_price"],
            "calories": item["calories"],
            "protein": item["protein"],
            "fat": item["fat"],
            "carbs": item["carbs"],
            "protein_source": item["protein_source"],
            "cuisine": item["cuisine"],
        }
        dishes.append(dish)

    dataset = {
        "metadata": {
            "description": "База блюд для задачи многокритериального формирования недельного меню",
            "variant": 6,
            "total_dishes": len(dishes),
            "categories": {
                "breakfast": sum(1 for d in dishes if d["category"] == "breakfast"),
                "lunch": sum(1 for d in dishes if d["category"] == "lunch"),
                "dinner": sum(1 for d in dishes if d["category"] == "dinner"),
            },
            "daily_targets": {
                "calories": 2200.0,
                "protein": 95.0,
                "fat": 75.0,
                "carbs": 280.0,
            },
            "weekly_targets": {
                "calories": 2200.0 * 7,
                "protein": 95.0 * 7,
                "fat": 75.0 * 7,
                "carbs": 280.0 * 7,
            },
            "tolerance_percentage": 0.05,
        },
        "dishes": dishes,
    }

    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with out_file.open("w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    print(f"Датасет успешно сформирован: {out_file}")
    print(f"Всего блюд: {len(dishes)}")
    for cat in ["breakfast", "lunch", "dinner"]:
        cat_dishes = [d for d in dishes if d["category"] == cat]
        prices = [d["price"] for d in cat_dishes]
        print(f" - {cat:10s}: {len(cat_dishes)} блюд, цены: {min(prices)} - {max(prices)} руб.")

    return dataset


if __name__ == "__main__":
    generate_dataset()

